// Bundle src/server/main.ts (and every dependency) into one CommonJS file inside the plugin,
// with the built view HTML inlined as a string. Plugins are copied as-is with no install
// step, so this file must run with plain `node` and nothing else.
//
// CommonJS, not ESM: the plugin folder has no package.json, so Node treats .js as CJS.
import { build } from 'esbuild';
import { existsSync, readFileSync, statSync } from 'node:fs';

const html = 'dist/ui/mcp-app.html';
if (!existsSync(html)) {
  console.error(`${html} is missing; run "npm run build:ui" first.`);
  process.exit(1);
}

const manifest = JSON.parse(readFileSync('plugins/domain-visualizer/.claude-plugin/plugin.json', 'utf8'));
const outfile = 'plugins/domain-visualizer/server/server.js';

await build({
  entryPoints: ['src/server/main.ts'],
  outfile,
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  loader: { '.html': 'text' },
  define: { __VERSION__: JSON.stringify(manifest.version) },
  legalComments: 'none',
  minify: false,
  banner: { js: `// domain-visualizer MCP server ${manifest.version}. Generated by scripts/build-server.mjs; do not edit.` },
  logLevel: 'info',
});

console.log(`${outfile}: ${(statSync(outfile).size / 1024).toFixed(0)} KB`);
